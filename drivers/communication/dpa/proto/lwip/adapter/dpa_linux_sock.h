
#ifndef DPA_LINUX_SOCK_H_
#define DPA_LINUX_SOCK_H_

#define DPA_SOCK_MAX_MSG_FRAGS 3 /* msg for 3 * maa data */
#define DPA_SOCK_SIN6_LEN_RFC2133 24

/* following value must be same to lwip define */
#define DPA_AF_INET 2
#define DPA_AF_INET6 10

#define DPA_SOCK_STREAM 1
#define DPA_SOCK_DGRAM 2
#define DPA_SOCK_RAW 3

#define DPA_SOCK_MSG_PEEK 0x01
#define DPA_SOCK_MSG_WAITALL 0x02
#define DPA_SOCK_MSG_OOB 0x04
#define DPA_SOCK_MSG_DONTWAIT 0x08
#define DPA_SOCK_MSG_MORE 0x10
#define DPA_SOCK_MSG_ZEROCOPY 0x4000000

#define DPA_SOCK_SOL_SOCKET 0xfff

/* level: SOL_SOCKET */
#define DPA_SOCK_SO_DEBUG 0x0001
#define DPA_SOCK_SO_ACCEPTCONN 0x0002
#define DPA_SOCK_SO_DONTROUTE 0x0010
#define DPA_SOCK_SO_USELOOPBACK 0x0040
#define DPA_SOCK_SO_LINGER 0x0080
#define DPA_SOCK_SO_DONTLINGER ((int)(~DPA_SOCK_SO_LINGER))
#define DPA_SOCK_SO_OOBINLINE 0x0100
#define DPA_SOCK_SO_REUSEPORT 0x0200
#define DPA_SOCK_SO_SNDBUF 0x1001
#define DPA_SOCK_SO_RCVBUF 0x1002
#define DPA_SOCK_SO_SNDLOWAT 0x1003
#define DPA_SOCK_SO_RCVLOWAT 0x1004
#define DPA_SOCK_SO_SNDTIMEO 0x1005
#define DPA_SOCK_SO_RCVTIMEO 0x1006
#define DPA_SOCK_SO_ERROR 0x1007
#define DPA_SOCK_SO_TYPE 0x1008
#define DPA_SOCK_SO_CONTIMEO 0x1009
#define DPA_SOCK_SO_NO_CHECK 0x100a

#define DPA_SOCK_SO_REUSEADDR 0x0004
#define DPA_SOCK_SO_KEEPALIVE 0x0008
#define DPA_SOCK_SO_BROADCAST 0x0020

/* level: SOL_SOCKET */
#define DPA_SOL_SOCKET 0xFFF
#define DPA_SO_BINDTODEVICE 0x100B

/* level: IPPROTO_IP */
#define DPA_SOCK_IP_MULTICAST_TTL 5
#define DPA_SOCK_IP_MULTICAST_IF 6
#define DPA_SOCK_IP_MULTICAST_LOOP 7

/* level: IPPROTO_TCP */
#define DPA_SOCK_TCP_NODELAY 0x01
#define DPA_SOCK_TCP_KEEPALIVE 0x02
#define DPA_SOCK_TCP_KEEPIDLE 0x03
#define DPA_SOCK_TCP_KEEPINTVL 0x04
#define DPA_SOCK_TCP_KEEPCNT 0x05
#define DPA_SOCK_TCP_MAXSEG 0x06

/* level: IPPROTO_IPV6 */
#define DPA_SOCK_IPV6_CHECKSUM 7
#define DPA_SOCK_IPV6_V6ONLY 27
#define DPA_SOCK_IPV6_TCLASS 67

/* ioctl cmd */
#define DPA_SOCK_IOCPARM_MASK 0x7fU
#define DPA_SOCK_IOC_VOID 0x20000000UL
#define DPA_SOCK_IOC_OUT 0x40000000UL
#define DPA_SOCK_IOC_IN 0x80000000UL
#define DPA_SOCK_IOC_INOUT (DPA_SOCK_IOC_IN | DPA_SOCK_IOC_OUT)
#define DPA_SOCK_IO(x, y) (DPA_SOCK_IOC_VOID | ((x) << 8) | (y))
#define DPA_SOCK_IOR(x, y, t) (DPA_SOCK_IOC_OUT | (((long)sizeof(t) & DPA_SOCK_IOCPARM_MASK) << 16) | ((x) << 8) | (y))
#define DPA_SOCK_IOW(x, y, t) (DPA_SOCK_IOC_IN | (((long)sizeof(t) & DPA_SOCK_IOCPARM_MASK) << 16) | ((x) << 8) | (y))

#define DPA_SOCK_FIONREAD DPA_SOCK_IOR('f', 127, unsigned long)
#define DPA_SOCK_FIONBIO DPA_SOCK_IOW('f', 126, unsigned long)

#define DPA_SOCK_ERRNO_EAGAIN (-11)

#endif /* DPA_LINUX_SOCK_H_ */
