#ifndef __XLOADER_MEMORY_MAP_H__
#define __XLOADER_MEMORY_MAP_H__ 
#include <soc_acpu_baseaddr_interface.h>
#define SIZE_1KB 1024
#define SIZE_4KB 4096
#define AP_CERT_SIZE (8 * SIZE_1KB)
#define MSPC_CERT_SIZE (12 * SIZE_1KB)
#ifdef XLOADER_MSPC_CERT_ENABLE
#define XLOADER_CERT_SIZE (AP_CERT_SIZE + MSPC_CERT_SIZE)
#else
#define XLOADER_CERT_SIZE (AP_CERT_SIZE)
#endif
#define SEC_RGN_EL3_PAGE_TABLE 5
#define SEC_RGN_EL1_PAGE_TABLE 6
#define SC_DRAM_BASE SOC_ACPU_SC_DATA_BASE_ADDR
#define SC_DRAM_SIZE (SIZE_1KB * SIZE_1KB)
#define EL3_STACK_BASE (SC_DRAM_BASE)
#define EL3_STACK_SIZE (2 * SIZE_4KB)
#define EL3_STACK_END (EL3_STACK_BASE + EL3_STACK_SIZE)
#define EL1_STACK_BASE (EL3_STACK_END)
#define EL1_STACK_SIZE (2 * SIZE_4KB)
#define EL1_STACK_END (EL1_STACK_BASE + EL1_STACK_SIZE)
#define EL3_STATIC_AREA_BASE (EL1_STACK_END)
#define EL3_STATIC_AREA_SIZE (2 * SIZE_4KB)
#define EL3_STATIC_AREA_END (EL3_STATIC_AREA_BASE + EL3_STATIC_AREA_SIZE)
#define EL1_STATIC_AREA_BASE (EL3_STATIC_AREA_END)
#define EL1_STATIC_AREA_SIZE (2 * SIZE_4KB)
#define EL1_STATIC_AREA_END (EL1_STATIC_AREA_BASE + EL1_STATIC_AREA_SIZE)
#define EL3_PAGE_TABLE_BASE (EL1_STATIC_AREA_END)
#define EL3_PAGE_TABLE_SIZE (4 * SIZE_4KB)
#define EL3_PAGE_TABLE_END (EL3_PAGE_TABLE_BASE + EL3_PAGE_TABLE_SIZE)
#define EL1_PAGE_TABLE_BASE (EL3_PAGE_TABLE_END)
#define EL1_PAGE_TABLE_SIZE (4 * SIZE_4KB)
#define EL1_PAGE_TABLE_END (EL1_PAGE_TABLE_BASE + EL1_PAGE_TABLE_SIZE)
#define STATIC_ERROR_CODE_ADDR (EL1_PAGE_TABLE_END)
#define STATIC_ERROR_CODE_SIZE (2 * SIZE_4KB)
#define STATIC_EXT_ERROR_CODE_ADDR (STATIC_ERROR_CODE_ADDR + 0x4)
#define RAM_BOOT_TIME_KEYPOINT_BASE (STATIC_EXT_ERROR_CODE_ADDR + 0x4)
#define RAM_BOOT_TIME_KEYPOINT_SIZE (0x10)
#define SEC_PRELOADER_IMAGE_MAX_SIZE (300 * SIZE_1KB)
#define PRELOADER_IMAGE_MAX_SIZE (SEC_PRELOADER_IMAGE_MAX_SIZE - AP_CERT_SIZE - MSPC_CERT_SIZE)
#define SEC_PRELOADER_IMG_BASE (STATIC_ERROR_CODE_ADDR + STATIC_ERROR_CODE_SIZE)
#define PRELOADER_IMAGE_BASE (SEC_PRELOADER_IMG_BASE + AP_CERT_SIZE + MSPC_CERT_SIZE)
#define PRELOADER_END_ADDR (SEC_PRELOADER_IMG_BASE + SEC_PRELOADER_IMAGE_MAX_SIZE)
#define EMPOWER_CERT_BASE PRELOADER_END_ADDR
#define EMPOWER_CERT_SIZE (2 * SIZE_4KB)
#define SECDBG_CERT_BASE (EMPOWER_CERT_BASE + EMPOWER_CERT_SIZE)
#define SECDBG_CERT_SIZE (2 * SIZE_4KB)
#define UAPP_BINDFILE_BASE (SECDBG_CERT_BASE + SECDBG_CERT_SIZE)
#define UAPP_BINDFILE_SIZE (3 * SIZE_4KB)
#define RESERVED_BASE (UAPP_BINDFILE_BASE + UAPP_BINDFILE_SIZE)
#define RESERVED_SIZE (4 * SIZE_4KB)
#define SEC_XLOADER_IMG_BASE (RESERVED_BASE + RESERVED_SIZE)
#define SEC_XLOADER_IMAGE_MAX_SIZE (712 * SIZE_1KB)
#define XLOADER_END_ADDR (SEC_XLOADER_IMG_BASE + SEC_XLOADER_IMAGE_MAX_SIZE)
#define XLOADER_IMAGE_BASE (SEC_XLOADER_IMG_BASE)
#define XLOADER_IMAGE_MAX_SIZE (SEC_XLOADER_IMAGE_MAX_SIZE - XLOADER_CERT_SIZE)
#define XLOADER_CERT_BASE (XLOADER_END_ADDR - XLOADER_CERT_SIZE)
#define EL3_BSS_BASE (XLOADER_END_ADDR)
#define EL3_BSS_SIZE (15 * SIZE_4KB)
#define EL3_BSS_END (EL3_BSS_BASE + EL3_BSS_SIZE)
#define EL1_BSS_BASE (EL3_BSS_END)
#define EL1_BSS_SIZE (SIZE_4KB)
#define EL1_BSS_END (EL1_BSS_BASE + EL1_BSS_SIZE)
#define PG_INFO_SHARE_MEM_BASE (EL1_BSS_END)
#define PG_INFO_SHARE_MEM_SIZE (SIZE_4KB)
#define LOG_BUFF_BASE (PG_INFO_SHARE_MEM_BASE + PG_INFO_SHARE_MEM_SIZE)
#define LOG_BUFF_SIZE (2 * SIZE_4KB)
#define RESERVED_DDR_XPU_BASE (LOG_BUFF_BASE + LOG_BUFF_SIZE)
#define RESERVED_DDR_XPU_SIZE (320 * SIZE_1KB)
#define RESERVED_DDR_MNTN_BASE (RESERVED_DDR_XPU_BASE + RESERVED_DDR_XPU_SIZE)
#define RESERVED_DDR_MNTN_SIZE (240 * SIZE_1KB)
#define SEC_WORKSPACE_BASE (RESERVED_DDR_MNTN_BASE + RESERVED_DDR_MNTN_SIZE)
#define SEC_WORKSPACE_SIZE (SIZE_4KB)
#define SEC_INFO_CTX_BASE (SEC_WORKSPACE_BASE + SEC_WORKSPACE_SIZE)
#define SEC_INFO_CTX_SIZE (SIZE_1KB)
#define SEC_STATIC_AREA_BASE (SEC_INFO_CTX_BASE + SEC_INFO_CTX_SIZE)
#define SEC_STATIC_AREA_SIZE (2 * SIZE_4KB + 3 * SIZE_1KB)
#define SUB_RESERVED_BOOTTIME_BASE (SEC_STATIC_AREA_BASE + SEC_STATIC_AREA_SIZE)
#define SUB_RESERVED_BOOTTIME_SIZE (3 * SIZE_4KB)
#define SUB_RESERVED_BOOTTIME_XLOADER_BASE (SUB_RESERVED_BOOTTIME_BASE)
#define SUB_RESERVED_BOOTTIME_XLOADER_SIZE (2 * SIZE_4KB)
#define SUB_RESERVED_BOOTTIME_PRELOADER_BASE (SUB_RESERVED_BOOTTIME_XLOADER_BASE + SUB_RESERVED_BOOTTIME_XLOADER_SIZE)
#define SUB_RESERVED_BOOTTIME_PRELOADER_SIZE (SIZE_4KB)
#define SC_DRAM_END (SUB_RESERVED_BOOTTIME_BASE + SUB_RESERVED_BOOTTIME_SIZE)
#define UFS_STATIC_WORK_SPACE_BASE (EL3_STATIC_AREA_BASE)
#define UFS_STATIC_WORK_SPACE_SIZE (0x1400)
#define DCV_STATIC_AREA_BASE (UFS_STATIC_WORK_SPACE_BASE + UFS_STATIC_WORK_SPACE_SIZE)
#define DCV_STATIC_AREA_SIZE (0x400)
#define UAPP_STATIC_AREA_BASE (DCV_STATIC_AREA_BASE + DCV_STATIC_AREA_SIZE)
#define UAPP_STATIC_AREA_SIZE (0x200)
#define SECBOOT_STATIC_AREA_BASE (UAPP_STATIC_AREA_BASE + UAPP_STATIC_AREA_SIZE)
#define SECBOOT_STATIC_AREA_SIZE (0x200)
#define SECURE_ENGINE_GM_WORK_SPACE_BASE (RESERVED_BASE)
#define SECURE_ENGINE_GM_WORK_SPACE_SIZE (0x1000)
#define DICE_WORK_SPACE_BASE (SECURE_ENGINE_GM_WORK_SPACE_BASE + SECURE_ENGINE_GM_WORK_SPACE_SIZE)
#define DICE_WORK_SPACE_SIZE (0x1400)
#define USB_STATIC_WORK_SPACE_BASE (EL1_STATIC_AREA_BASE)
#define USB_STATIC_WORK_SPACE_SIZE (0x1400)
#endif
