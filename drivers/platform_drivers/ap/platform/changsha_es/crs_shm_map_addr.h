#ifndef __COMPUTE_RESOURCE_SCHEDULER_SHM_MAP_ADDR_H__
#define __COMPUTE_RESOURCE_SCHEDULER_SHM_MAP_ADDR_H__ 
#include <assert.h>
#include <global_ddr_map.h>
#define SHM_CRS_BEGIN (RESERVED_CRS_SHARE_PHYMEM_BASE)
#define SHM_CRS_HECA_BASE (RESERVED_CRS_SHARE_PHYMEM_BASE)
#define SHM_CRS_HECA_SIZE (0x1000)
#define SHM_CRS_DEADLINE_BASE (SHM_CRS_HECA_BASE + SHM_CRS_HECA_SIZE)
#define SHM_CRS_DEADLINE_SIZE (0x5000)
#define SHM_CRS_SCHEDUTIL_BASE (SHM_CRS_DEADLINE_BASE + SHM_CRS_DEADLINE_SIZE)
#define SHM_CRS_SCHEDUTIL_SIZE (0x1000)
#define SHM_CRS_BASIC_BASE (SHM_CRS_SCHEDUTIL_BASE + SHM_CRS_SCHEDUTIL_SIZE)
#define SHM_CRS_BASIC_SIZE (0x1000)
#define SHM_CRS_END (SHM_CRS_BASIC_BASE + SHM_CRS_BASIC_SIZE)
static_assert(SHM_CRS_END <= (RESERVED_CRS_SHARE_PHYMEM_BASE + RESERVED_CRS_SHARE_PHYMEM_SIZE), "Shared mem overflow");
static_assert(SHM_CRS_END <= 0x3FFFFFFF && SHM_CRS_BEGIN >= 0x20000000, "lpmcu crs shm not in default window range");
#define SHM_CRS_UNUSED_SIZE \
 (RESERVED_CRS_SHARE_PHYMEM_SIZE - SHM_CRS_HECA_SIZE - SHM_CRS_DEADLINE_SIZE - SHM_CRS_SCHEDUTIL_SIZE - \
  SHM_CRS_BASIC_SIZE)
#endif
