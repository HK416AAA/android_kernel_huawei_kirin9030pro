#ifndef __XPU_CPU_SRAM_H__
#define __XPU_CPU_SRAM_H__ 
#include <soc_acpu_baseaddr_interface.h>
#include <soc_lpmcu_baseaddr_interface.h>
#define __PRINT_MACRO(x) #x
#define PRINT_MACRO(x) #x"="__PRINT_MACRO(x)
#if defined(CONFIG_ACPU_DIRECT_ACCESS_CXPU)
#define CXPU_SRAM_BASE SOC_ACPU_CPU_LPCTRL_AHB_BASE_ADDR
#elif defined(CONFIG_LPMCU_DIRECT_ACCESS_CXPU)
#define CXPU_SRAM_BASE SOC_LPMCU_CPU_LPCTRL_AHB_BASE_ADDR
#else
#define CXPU_SRAM_BASE 0
#endif
#define CXPU_SRAM_SIZE 0x14000U
#define CXPU_PROG_HEAD_BASE (CXPU_SRAM_BASE)
#define CXPU_PROG_HEAD_SIZE 0x40
#define CXPU_PROFILE_BASE (CXPU_PROG_HEAD_BASE + CXPU_PROG_HEAD_SIZE)
#define CXPU_PROFILE_SIZE ((0x440 * 4) - 0x80)
#define CXPU_SHARE_GXPU_BASE (CXPU_PROFILE_BASE + CXPU_PROFILE_SIZE)
#define CXPU_SHARE_GXPU_SIZE 0x20
#define CXPU_SHARE_MEM_BASE (CXPU_SHARE_GXPU_BASE + CXPU_SHARE_GXPU_SIZE)
#define CXPU_SHARE_MEM_SIZE 0x80
#define CXPU_SEC_DATA_BASE (CXPU_SHARE_MEM_BASE + CXPU_SHARE_MEM_SIZE)
#define CXPU_SEC_DATA_RSV_SIZE 0x0
#define CXPU_SEC_DATA_SIZE (0x4CE0 - CXPU_SEC_DATA_RSV_SIZE)
#define CXPU_SEC_SDATA_BASE (CXPU_SEC_DATA_BASE + CXPU_SEC_DATA_SIZE + CXPU_SEC_DATA_RSV_SIZE)
#define CXPU_SEC_SDATA_SIZE 0x0
#define CXPU_SEC_CODE_BASE (CXPU_SEC_SDATA_BASE + CXPU_SEC_SDATA_SIZE)
#define CXPU_SEC_CODE_RSV_SIZE 0x0
#define CXPU_SEC_CODE_SIZE (0xE1C0 - CXPU_SEC_CODE_RSV_SIZE)
#define CXPU_SEC_STACK_SIZE 0x500
#define CXPU_MAP_END (CXPU_SEC_CODE_BASE + CXPU_SEC_CODE_SIZE + CXPU_SEC_CODE_RSV_SIZE)
#if (CXPU_MAP_END != (CXPU_SRAM_BASE + CXPU_SRAM_SIZE))
        
#pragma message(PRINT_MACRO(CXPU_SEC_STACK_BASE + CXPU_SEC_STACK_SIZE))
#error "ram overflow!!!"
#endif
#define CXPU_CERT_SIZE (8 * 1024)
#define SEC_CXPU_IMAGE_ADDR (SOC_ACPU_CPU_LPCTRL_AHB_BASE_ADDR)
#define SEC_CXPU_IMAGE_SIZE (CXPU_SRAM_SIZE)
#define SEC_CXPU_IMAGE_END (SEC_CXPU_IMAGE_ADDR + SEC_CXPU_IMAGE_SIZE)
#define LOAD_CXPU_IMG_ADDR (SEC_CXPU_IMAGE_ADDR)
#define LOAD_CXPU_IMG_SIZE (SEC_CXPU_IMAGE_SIZE)
#define LOAD_CXPU_CERT_ADDR (RESERVED_FASTBOOT_PHYMEM_BASE + RESERVED_FASTBOOT_PHYMEM_SIZE)
#define LOAD_CXPU_CERT_SIZE (CXPU_CERT_SIZE)
#define LPMCU_CXPU_MNTN_CFG_BASE SOC_LPMCU_CPU_LPCTRL_APB_BASE_ADDR
#define LPMCU_CXPU_MNTN_PMC_DUMP_ADDR (SOC_ACPU_CPU_LPCTRL_APB_BASE_ADDR + 0x5000)
#define LPMCU_CXPU_MNTN_PMC_DUMP_SIZE (4 * 1024U)
#define LPMCU_CXPU_MNTN_TCM_DUMP_ADDR SOC_ACPU_CPU_LPCTRL_AHB_BASE_ADDR
#define LPMCU_CXPU_MNTN_TCM_DUMP_SIZE (CXPU_SEC_CODE_BASE - CXPU_SRAM_BASE)
#endif
