#define temp2adc(temp) (((temp) - TSENS_TEMP_START_VALUE - TSENSOR_DELTA_VAL) * (TSENSOR_ADC_MAX - TSENS_ADC_START_VALUE) / \
   (TSENS_TEMP_END_VALUE - TSENS_TEMP_START_VALUE) + TSENS_ADC_START_VALUE)
#define adc2temp(adc) (((adc) - TSENS_ADC_START_VALUE) * (TSENS_TEMP_END_VALUE - TSENS_TEMP_START_VALUE) / \
         (TSENSOR_ADC_MAX - TSENS_ADC_START_VALUE) + TSENS_TEMP_START_VALUE + TSENSOR_DELTA_VAL)
#define temp2dadc(temp) (((temp) - DIGTSENS_TEMP_BIAS) * (DIGTSENSOR_ADC_MAX - DIGTSENS_ADC_START_VALUE) / \
   DIGTSENS_TEMP_DELTA + DIGTSENS_ADC_START_VALUE)
#define dadc2temp(adc) (((adc) - DIGTSENS_ADC_START_VALUE) * DIGTSENS_TEMP_DELTA / \
         (DIGTSENSOR_ADC_MAX - DIGTSENS_ADC_START_VALUE) + DIGTSENS_TEMP_BIAS)
