#ifndef __MEDIA_XPU_CLOCK_H__
#define __MEDIA_XPU_CLOCK_H__ 
#define CLK_ID_TO_XPU_START (1 << 7)
enum clk_id_to_xpu {
    CLK_DSS_CORE_TO_XPU = CLK_ID_TO_XPU_START,
    CLK_VENC_TO_XPU,
    CLK_VDEC_PXPC_TO_XPU,
    CLK_AAE_CORE_TO_XPU,
    CLK_ISP_RT_TO_XPU,
    CLK_ISP_NRT_TO_XPU,
    CLK_ISP_SRT_TO_XPU,
    CLK_OISP_TO_XPU,
    CLK_IPP_TO_XPU,
    CLK_ISPSPI_TO_XPU,
    CLK_GIC_ISPCPU_TO_XPU,
    CLK_PERIPH_ISPCPU_TO_XPU,
    CLK_CSI_IDI_TO_XPU,
    CLK_DSS_VIVO_TO_XPU,
    CLK_ID_TO_XPU_END,
};
enum xpu_clk_ops_id {
    XPU_CLK_INIT = 0xF0,
    XPU_CLK_ENABLE,
    XPU_CLK_DISABLE,
    XPU_CLK_DUMP,
    XPU_CLK_ALL_DUMP,
    XPU_CLK_OPS_ID_MAX,
};
#define XPU_SUCC 0x00
#define XPU_ERROR_BAD_PARA 0x01
#define XPU_ERROR_BAD_OPS 0x02
#define XPU_ERROR_TIMEOUT 0x03
#define XPU_ERROR_NOTEXIT 0x04
#define XPU_ERROR_INVALID 0x05
#define XPU_ERROR_LOW_TEMP 0x06
#endif
