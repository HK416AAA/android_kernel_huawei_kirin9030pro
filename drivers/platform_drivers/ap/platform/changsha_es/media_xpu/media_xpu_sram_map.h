#ifndef __MEDIA_XPU_SRAM_MAP_H__
#define __MEDIA_XPU_SRAM_MAP_H__ 
#include <soc_media_xpu_baseaddr_interface.h>
#define MEDIA_XPU_SRAM_SIZE 0X18000
#define MEDIA_XPU_CODE_BASE MEDIA_XPU_SRAM_BASE
#define MEDIA_XPU_CODE_SIZE 0xC000
#define MEDIA_XPU_DATA_BASE (MEDIA_XPU_CODE_BASE + MEDIA_XPU_CODE_SIZE)
#define MEDIA_XPU_DATA_SIZE 0x5000
#define MEDIA_XPU_BSS_BASE (MEDIA_XPU_DATA_BASE + MEDIA_XPU_DATA_SIZE)
#define MEDIA_XPU_BSS_SIZE 0x1000
#define MEDIA_XPU_STACK_BASE (MEDIA_XPU_BSS_BASE + MEDIA_XPU_BSS_SIZE)
#define MEDIA_XPU_STACK_SIZE 0x1000
#define MEDIA_XPU_LOG_BASE (MEDIA_XPU_STACK_BASE + MEDIA_XPU_STACK_SIZE)
#define MEDIA_XPU_LOG_SIZE 0x2000
#define MEDIA_XPU_MNTN_BASE (MEDIA_XPU_LOG_BASE + MEDIA_XPU_LOG_SIZE)
#define MEDIA_XPU_MNTN_SIZE 0x3000
#define MEDIA_XPU_IRQ_BASE (MEDIA_XPU_MNTN_BASE + 0x0)
#define MEDIA_XPU_IRQ_SIZE 0x1000
#define MEDIA_XPU_CLK_BASE (MEDIA_XPU_IRQ_BASE + MEDIA_XPU_IRQ_SIZE)
#define MEDIA_XPU_CLK_SIZE 0x1000
#define MEDIA_XPU_REGULATOR_BASE (MEDIA_XPU_CLK_BASE + MEDIA_XPU_CLK_SIZE)
#define MEDIA_XPU_REGULATOR_SIZE 0x1000
#define MEDIA_XPU_SRAM_END (MEDIA_XPU_REGULATOR_BASE + MEDIA_XPU_REGULATOR_SIZE)
#if ((MEDIA_XPU_SRAM_END - MEDIA_XPU_MNTN_BASE) > MEDIA_XPU_MNTN_SIZE)
    #error "media xpu mntn overflow!!!"
#endif
#if ((MEDIA_XPU_SRAM_END - MEDIA_XPU_SRAM_BASE) > MEDIA_XPU_SRAM_SIZE)
    #error "media xpu ram overflow!!!"
#endif
#define MEDIA_XPU_CERT_SIZE (8 * SZ_1KB)
#define SEC_MEDIA_XPU_IMAGE_ADDR (MEDIA_XPU_SRAM_BASE)
#define SEC_MEDIA_XPU_IMAGE_SIZE (MEDIA_XPU_SRAM_SIZE)
#define SEC_MEDIA_XPU_IMAGE_END (SEC_MEDIA_XPU_IMAGE_ADDR + SEC_MEDIA_XPU_IMAGE_SIZE)
#define LOAD_MEDIA_XPU_IMG_ADDR (SEC_MEDIA_XPU_IMAGE_ADDR)
#define LOAD_MEDIA_XPU_IMG_SIZE (SEC_MEDIA_XPU_IMAGE_SIZE)
#define LOAD_MEDIA_XPU_CERT_ADDR (RESERVED_FASTBOOT_PHYMEM_BASE + RESERVED_FASTBOOT_PHYMEM_SIZE)
#define LOAD_MEDIA_XPU_CERT_SIZE (MEDIA_XPU_CERT_SIZE)
#endif
