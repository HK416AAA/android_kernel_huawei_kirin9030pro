#ifndef __XLOADER_MEMORY_MAP_H__
#define __XLOADER_MEMORY_MAP_H__ 
#define SIZE_1KB 1024
#define AP_VRL_SIZE (8 * SIZE_1KB)
#define MSPC_VRL_SIZE (12 * SIZE_1KB)
#ifdef XLOADER_MSPC_VRL_ENABLE
#define VRL_SIZE (AP_VRL_SIZE + MSPC_VRL_SIZE)
#else
#define VRL_SIZE AP_VRL_SIZE
#endif
#define XLOADER_IMAGE_MAX_SIZE (276 * SIZE_1KB)
#define SEC_XLOADER_IMAGE_MAX_SIZE (XLOADER_IMAGE_MAX_SIZE + VRL_SIZE)
#define XLOADER_LOAD_VRL_ADDR 0x23000
#define XLOADER_LOAD_IMAGE_ADDR (XLOADER_LOAD_VRL_ADDR + VRL_SIZE)
#define SECINFO_CTX_LPRAM_ADDR (XLOADER_LOAD_IMAGE_ADDR + XLOADER_IMAGE_MAX_SIZE)
#define SECINFO_CTX_LPRAM_SIZE (SIZE_1KB)
#define LOG_BUFF_BASE (SECINFO_CTX_LPRAM_ADDR + SECINFO_CTX_LPRAM_SIZE)
#define XLOADER_LOG_BUFF_SIZE (8 * SIZE_1KB)
#define LPRAM_SOC_SPEC_INFO_ADDR 0x70000
#define LPRAM_SOC_SPEC_INFO_SIZE (4 * SIZE_1KB)
#if (LOG_BUFF_BASE + XLOADER_LOG_BUFF_SIZE >= LPRAM_SOC_SPEC_INFO_ADDR)
#error xloader memory map error
#endif
#endif
