#ifndef __DDR_TMPBUFFER_MAP_H__
#define __DDR_TMPBUFFER_MAP_H__ 
#include "ddr_xpu_sram_map.h"
#define DDR_TMPBUFFER_BASE 0xD012D000
#define DDR_TMPBUFFER_MAX_SIZE 0x50000
#define DDR_TMPBUFFER_ADDITION_MAP 0xC0000000
#define DDR_TMPBUFFER_END (DDR_TMPBUFFER_BASE + DDR_TMPBUFFER_MAX_SIZE)
#define SEC_CERT_SIZE 0x2000
#define DDR_TMPBUFFER_XPU_CORE_WITH_SEC_CERT_BASE DDR_TMPBUFFER_BASE
#define DDR_TMPBUFFER_XPU_CORE_BASE (DDR_TMPBUFFER_BASE + SEC_CERT_SIZE)
#define DDR_XPU_CORE_IMG_MAX_SIZE DDR_XPU_SRAM_SIZE
#define DDR_TMPBUFFER_XPU_ADDITION_BASE (DDR_TMPBUFFER_XPU_CORE_BASE + DDR_XPU_CORE_IMG_MAX_SIZE - DDR_TMPBUFFER_ADDITION_MAP)
#define DDR_XPU_ADDITION_IMG_MAX_SIZE ((DDR_TMPBUFFER_MAX_SIZE) - (DDR_XPU_CORE_IMG_MAX_SIZE) - (SEC_CERT_SIZE))
#define DDR_TMPBUFFER_XPU_IMAGE_BASE ((DDR_TMPBUFFER_BASE) + (SEC_CERT_SIZE))
#define DDR_TMPBUFFER_XPU_IMAGE_SIZE ((DDR_XPU_CORE_IMG_MAX_SIZE) + (DDR_XPU_ADDITION_IMG_MAX_SIZE))
#define UCE_CERT_SIZE 0x2000
#define DDR_UCE_BOOT_IMG_MAX_SIZE 0x10000
#define DDR_UCE_RUNTIME_IMG_MAX_SIZE 0x10000
#define DDR_UCE_MERGE_IMG_MAX_SIZE ((DDR_UCE_BOOT_IMG_MAX_SIZE) + (DDR_UCE_RUNTIME_IMG_MAX_SIZE))
#define DDR_TMPBUFFER_UCE_MERGE_IMAGE_WITH_SEC_CERT_BASE \
    ((DDR_TMPBUFFER_END) - (DDR_XPU_ADDITION_IMG_MAX_SIZE) - (DDR_UCE_MERGE_IMG_MAX_SIZE) - (UCE_CERT_SIZE))
#define DDR_TMPBUFFER_UCE_MERGE_IMAGE_BASE ((DDR_TMPBUFFER_END) - (DDR_XPU_ADDITION_IMG_MAX_SIZE) - (DDR_UCE_MERGE_IMG_MAX_SIZE))
#define TRAIN_PARAM_SEC_SIZE 0x8
#define DDR_TMPBUFFER_TRAIN_PARAM_WITH_SEC_CERT_BASE DDR_TMPBUFFER_BASE
#define DDR_TMPBUFFER_TRAIN_PARAM_BASE ((DDR_TMPBUFFER_BASE) + (TRAIN_PARAM_SEC_SIZE))
#define DDR_TRAIN_PARAM_MAX_SIZE ((DDR_TMPBUFFER_MAX_SIZE) - (DDR_XPU_ADDITION_IMG_MAX_SIZE) - (DDR_UCE_MERGE_IMG_MAX_SIZE))
#define LOAD_UCE_CERT_ADDR (DDR_TMPBUFFER_UCE_MERGE_IMAGE_WITH_SEC_CERT_BASE)
#define LOAD_UCE_CERT_SIZE (UCE_CERT_SIZE)
#define LOAD_UCE_IMG_ADDR (LOAD_UCE_CERT_ADDR + LOAD_UCE_CERT_SIZE)
#define LOAD_UCE_IMG_SIZE ((DDR_UCE_MERGE_IMG_MAX_SIZE) - (LOAD_UCE_CERT_SIZE))
#if (((DDR_XPU_SRAM_BASE) + (DDR_XPU_CORE_IMG_MAX_SIZE)) < DDR_XPU_CERT_BASE)
    #error "CORE_MAX is not enough!!"
#endif
#if (DDR_TMPBUFFER_XPU_ADDITION_BASE != (DDR_TMPBUFFER_BASE + SEC_CERT_SIZE + DDR_XPU_SRAM_SIZE - DDR_TMPBUFFER_ADDITION_MAP))
    #error "addtion tempbuffer map is not match xpu ld map!!"
#endif
#endif
